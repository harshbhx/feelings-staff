#!/usr/bin/env node
/**
 * One-off generator for the India (Gujarat) public-holiday suggestions.
 *
 *   pnpm gen:holidays
 *
 * Reads the `date-holidays` package (ISC code, CC-BY-3.0 data; see NOTICE), a dev
 * dependency only, and writes app/worker/seed/holidays-in.ts. That file is plain static
 * data: the Worker never imports date-holidays at runtime. Lunar festivals (Holi,
 * Janmashtami, Dussehra, Diwali) are not in the upstream data for Gujarat, so the owner
 * adds those each year in Settings, Holidays. Uttarayan falls on 14 January every year,
 * so it is added here.
 */
import { writeFileSync } from 'node:fs';
import Holidays from 'date-holidays';

const YEARS = [2026, 2027];
const OUT = new URL('../app/worker/seed/holidays-in.ts', import.meta.url);

const hd = new Holidays('IN', 'GJ', { types: ['public'] });
const byDate = new Map();
for (const year of YEARS) {
  byDate.set(`${year}-01-14`, 'Uttarayan');
  for (const h of hd.getHolidays(year)) {
    const date = h.date.slice(0, 10);
    if (!byDate.has(date)) byDate.set(date, h.name);
  }
}
const rows = [...byDate].sort(([a], [b]) => a.localeCompare(b));

const body = rows
  .map(([date, name]) => `  { date: '${date}', name: '${name.replace(/'/g, "\\'")}' },`)
  .join('\n');
writeFileSync(
  OUT,
  `/**
 * India (Gujarat) public holidays for 2026 and 2027, proposed to the owner during setup.
 * GENERATED by scripts/gen-holidays.mjs from date-holidays (ISC; data CC-BY-3.0, see
 * NOTICE). Do not edit by hand; run \`pnpm gen:holidays\`.
 */
export const HOLIDAYS_IN_GJ: readonly { readonly date: string; readonly name: string }[] = [
${body}
];
`,
);
process.stdout.write(`wrote ${rows.length} holidays to app/worker/seed/holidays-in.ts\n`);

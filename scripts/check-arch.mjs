#!/usr/bin/env node
/**
 * Architecture rules (PRD 10.8, 16.1), run in CI:
 * - raw D1 access (`.prepare(`, `.batch(` on env.DB / DB) only inside app/worker/db/, app/worker/seed/
 *   and tests; everything else goes through OrgDb / SystemDb.
 * - no test-route imports outside the worker's route index.
 * - no AI attribution strings anywhere in source.
 */
import { read, report, walk } from './lib.mjs';

const problems = [];
const worker = walk('app/worker', ['.ts']);
const RAW_DB = /\b(?:env|c\.env|ctx\.env)\.DB\.(?:prepare|batch|exec)\(/;

for (const f of worker) {
  const allowed =
    f.startsWith('app/worker/db/') ||
    f.startsWith('app/worker/seed/') ||
    f.includes('/test/') ||
    f.endsWith('.test.ts');
  const src = read(f);
  src.split('\n').forEach((line, i) => {
    if (!allowed && RAW_DB.test(line))
      problems.push(`${f}:${i + 1} raw env.DB access; use ctx.db (OrgDb) or ctx.sys (SystemDb)`);
  });
  if (
    /from ['"]\.\.?\/(?:\.\.\/)*test-routes['"]/.test(src) &&
    f !== 'app/worker/routes/index.ts'
  ) {
    problems.push(`${f}: imports test-routes`);
  }
}

const ATTRIBUTION =
  /(Co-Authored-By|Generated with \[?Claude|Generated by (Claude|ChatGPT|AI)|noreply@anthropic\.com)/i;
for (const f of [
  ...walk('app', ['.ts', '.tsx', '.json', '.html', '.css']),
  ...walk('packages', ['.ts', '.tsx', '.json', '.css']),
  ...walk('scripts', ['.mjs', '.ts']),
  ...walk('e2e', ['.ts']),
  ...walk('.github', ['.yml', '.yaml', '.md']),
]) {
  if (f === 'scripts/check-arch.mjs') continue;
  if (ATTRIBUTION.test(read(f))) problems.push(`${f}: AI attribution text`);
}

report('check-arch', problems);

const i18n = await createI18n('en');
const t: PayslipDocumentProps['t'] = (key, vars) => i18n.t(key, vars) as string;
const html = (el: Parameters<typeof renderToStaticMarkup>[0]) => renderToStaticMarkup(el);

describe('payslip template (PRD 4.14)', () => {
  it('O-14.2 has every field: org, person, days, rate, lines with formulas, totals, payment, balances, verify, footer', () => {
    const out = html(<PayslipDocument view={view} t={t} />);
    for (const text of [
      'Feelings Beauty Care',
      'Jamnagar',
      'Priya Shah',
      'FBC-001',
      'Stylist',
      '01-03-2024',
      'Days in month',
      'P 25 · H 1 · A 1',
      '₹483.87',
      'Salary',
      '₹15,000 a month',
      'Loss of pay',
      '₹15,000 ÷ 31 days × 1.5 days',
      'Gross pay',
      '₹15,000.00',
      'Total deductions',
      'Rounding',
      'Net pay',
      '₹14,274.00',
      'Paid on 02-11-2026 by UPI',
      'Casual leave',
      'Check this slip',
      'https://staff.test/v/abcdefghijklmnop',
      'Generated by Feelings Staff on 01-11-2026',
      '<svg',
    ]) {
      expect(out).toContain(text);
    }
    expect(out).not.toContain('fs-watermark');
  });

  it('O-13.4 a superseded payslip carries the watermark naming the next revision', () => {
    const out = html(<PayslipDocument view={{ ...view, status: 'superseded' }} t={t} />);
    expect(out).toContain('Replaced by revision 2');
  });

  it('shows that a draft is not final and hides the QR when there is no verify URL', () => {
    const out = html(
      <PayslipDocument
        view={{ ...view, status: 'draft', id: null, verifyUrl: null, paid: null }}
        t={t}
      />,
    );
    expect(out).toContain('Draft, not final');
    expect(out).toContain('Not paid yet.');
    expect(out).not.toContain('<svg');
  });

  it('O-14.4 the fallback page carries the notice and a print button', () => {
    const out = renderDocument(<PayslipDocument view={view} t={t} />, {
      title: 'Salary slip',
      lang: 'en',
      fallback: { notice: t('payslip:fallback.notice'), printLabel: t('payslip:fallback.print') },
    });
    expect(out.startsWith('<!doctype html>')).toBe(true);
    expect(out).toContain('Print or save as PDF');
    expect(out).toContain('window.print()');
    expect(out).toContain("'Plus Jakarta Sans'");
  });
});


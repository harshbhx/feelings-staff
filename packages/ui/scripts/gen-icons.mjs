  hourglass: 'hourglass',
  'map-pin': 'map-pin',
  navigation: 'navigation-arrow',
  'calendar-blank': 'calendar-blank',
  'calendar-check': 'calendar-check',
  'airplane-tilt': 'airplane-tilt',
  confetti: 'confetti',
  coffee: 'coffee',
  user: 'user',
  users: 'users',
  camera: 'camera',
  'qr-code': 'qr-code',
  scan: 'scan',
  fingerprint: 'fingerprint',
  lock: 'lock',
  bell: 'bell',
  gear: 'gear',
  'chart-bar': 'chart-bar',
  'currency-inr': 'currency-inr',
  'file-pdf': 'file-pdf',

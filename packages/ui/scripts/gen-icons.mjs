export function readPaths(dir) {
  const out = {};
  for (const [name, file] of Object.entries(ICON_FILES)) {
    const svg = readFileSync(join(dir, 'assets/regular', `${file}.svg`), 'utf8');
    const paths = [...svg.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((m) => m[1]);
    if (paths.length === 0) throw new Error(`no <path> in ${file}.svg`);
    out[name] = paths;
  }
  return out;
}

function writePathsModule(fileName, exportName, typeName, comment, entries) {
  const body = entries.map(([name, d]) => `  '${name}': ${JSON.stringify(d)},`).join('\n');
  const src = `/**
 * ${comment}
 * Generated by packages/ui/scripts/gen-icons.mjs; do not edit by hand.
 */
export const ${exportName} = {
${body}
} as const satisfies Record<string, readonly string[]>;

export type ${typeName} = keyof typeof ${exportName};
`;
  writeFileSync(join(here, `../src/icons/${fileName}`), src);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const paths = readPaths(pkg);
  for (const name of CORE_ICON_NAMES) {
    if (!(name in ICON_FILES)) throw new Error(`CORE_ICON_NAMES has an unknown icon: ${name}`);
  }
  const coreEntries = Object.entries(paths).filter(([name]) => CORE_ICON_NAMES.has(name));
  const restEntries = Object.entries(paths).filter(([name]) => !CORE_ICON_NAMES.has(name));

  writePathsModule(
    'paths-core.ts',
    'CORE_ICON_PATHS',
    'CoreIconName',
    'Phosphor regular icon paths (MIT, @phosphor-icons/core 2.1.1), viewBox 0 0 256 256.\n' +
      " * The staff-core set (see CORE_ICON_NAMES in scripts/gen-icons.mjs): kept eager so PRD 11.10's\n" +
      " * staff initial JS budget doesn't wait on a network round trip for the first paint.",
    coreEntries,
  );
  writePathsModule(
    'paths-rest.ts',
    'REST_ICON_PATHS',
    'RestIconName',
    'Phosphor regular icon paths (MIT, @phosphor-icons/core 2.1.1), viewBox 0 0 256 256.\n' +
      ' * Every icon outside the staff-core set (./paths-core): loaded on demand via\n' +
      " * `import('./paths-rest')`, never part of the staff initial chunk.",
    restEntries,
  );

  const names = Object.keys(paths);
  const namesBody = names.map((n) => `  '${n}',`).join('\n');
  const namesSrc = `/**
 * Every icon name, Phosphor regular (MIT, @phosphor-icons/core 2.1.1). Plain strings only (no path
 * data), so importing this costs nothing: it is how Icon.tsx exposes \`ICON_NAMES\`/\`IconName\`
 * without pulling in ./paths-rest. Generated by packages/ui/scripts/gen-icons.mjs; do not edit by
 * hand.
 */
export const ICON_NAMES = [
${namesBody}
] as const;

export type IconName = (typeof ICON_NAMES)[number];
`;
  writeFileSync(join(here, '../src/icons/names.ts'), namesSrc);

  console.info(
    `gen-icons: ${names.length} icons (${coreEntries.length} core, ${restEntries.length} lazy)`,
  );
}
